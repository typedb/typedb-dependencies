set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR/../../.."

# a manifest the sync no longer generates must go, whichever notice version it carries; a symlinked one must stay
LINKED_DIR="$(mktemp -d)"
trap 'rm -rf stale linked "$LINKED_DIR"' EXIT
mkdir -p stale && printf '\n# Generated by TypeDB Cargo sync tool.\n' > stale/Cargo.toml
printf '# Generated by TypeDB Cargo sync tool.\n' > "$LINKED_DIR/Cargo.toml"
mkdir -p linked && ln -s "$LINKED_DIR/Cargo.toml" linked/Cargo.toml
"$SCRIPT_DIR/sync.sh"
if [ -e stale/Cargo.toml ] || [ ! -L linked/Cargo.toml ]; then
    echo "VERIFY FAILED: stale generated manifest kept, or a symlinked manifest deleted" >&2
    exit 1
fi
rm -rf stale linked "$LINKED_DIR"

CHANGED="$(git status --porcelain -uall -- . | grep 'Cargo\.toml' || true)"
if [ -n "$CHANGED" ]; then
    echo "$CHANGED"
    git --no-pager diff -- '*Cargo.toml'
    git ls-files --others --exclude-standard -- '*Cargo.toml' | while read -r new_manifest; do
        git --no-pager diff --no-index /dev/null "$new_manifest" || true
    done
    echo "VERIFY FAILED: generated Cargo.toml files differ from the committed ones" >&2
    exit 1
fi
# a manifest can be deterministic and still wrong, so also check that cargo accepts it
cargo generate-lockfile --quiet
echo "VERIFY PASSED"
